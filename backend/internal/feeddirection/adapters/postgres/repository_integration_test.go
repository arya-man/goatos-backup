// The query has no COALESCE and no LEFT JOIN, and this is the proof: an unauthored cell is simply
// not in the map. The generator turns that absence into a BLOCKED quantity, which is what stops a
// shed from silently being fed nothing.
func TestUnauthoredCellIsAbsentFromTheSnapshotRatherThanZero(t *testing.T) {
	ctx := context.Background()
	repo, pool := setupFeedDirectionDB(t, ctx)

	// Concentrate is authored (as an explicit ZERO); Hybrid is not authored at all.
	if _, err := pool.Exec(ctx, `
INSERT INTO feed_ration_rates (tenant_id, park_id, ration_group_label, shed_tag_label, feed_item_label, grams_per_head, valid_from)
VALUES ($1::uuid, $2::uuid, 'Kid', 'K0', 'Concentrate', 0.000, DATE '2026-01-01')`,
		fdTenant, fdPark); err != nil {
		t.Fatalf("seed rate: %v", err)
	}

	snapshot, err := repo.LoadConfigSnapshot(ctx, fdTenant, fdPark, businessDay(2026, 7, 19))
	if err != nil {
		t.Fatalf("LoadConfigSnapshot: %v", err)
	}

	authoredZero, ok := snapshot.RatesByKey[domain.RateKey("Kid", "K0", "Concentrate")]
	if !ok {
		t.Fatal("an authored zero is a real rate and must be PRESENT in the snapshot")
	}
	if authoredZero.GramsPerHead != "0.000" {
		t.Fatalf("authored zero = %q, want \"0.000\"", authoredZero.GramsPerHead)
	}

	if _, ok := snapshot.RatesByKey[domain.RateKey("Kid", "K0", "Hybrid")]; ok {
		t.Fatal("an unauthored cell appeared in the snapshot; absence is the ONLY encoding of 'not configured'")
	}
}

