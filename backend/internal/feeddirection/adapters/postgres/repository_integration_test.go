// Proofs against the REAL schema (migration 000003).
//
// The generation rules themselves are proved without a database in ../../domain -- they are a pure
// function and should not need Docker. What only a database can prove is the boundary between Go
// and SQL, and there are three things there that would silently produce a WRONG FEED SHEET rather
// than an error:
//
//	KEY PARITY        -- the generator joins live free-text values to authored labels IN MEMORY,
//	                     using NormalizeConfigKey. The stored *_key columns are GENERATED by the
//	                     database's feed_config_norm(). If the two ever disagree by one character,
//	                     a perfectly well-authored shed silently BLOCKS. Nothing but a real database
//	                     can compare them.
//	EFFECTIVE DATING  -- the snapshot must load the rates in force ON THE TARGET DAY, not the
//	                     currently-open row. A fake would happily return whatever it was stocked
//	                     with and "prove" a back-dated regeneration that never happened.
//	ABSENCE           -- a cell with no row must be ABSENT from the map, never a zero. The query has
//	                     no COALESCE and no LEFT JOIN, and this is where that is verified.

const (
	// A dedicated uuid prefix (fd...) rather than the conventional 3001/4001 fixture ids. Those
	// collide with locations the baseline migration already seeds, which silently mixes 8 foreign
	// sheds into this park and makes the shed-page assertions meaningless.
	fdTenant = "fd000000-0000-4000-8000-000000000001"
	fdPark   = "fd000000-0000-4000-8000-000000003001"
	fdShedA  = "fd000000-0000-4000-8000-000000004001"
	fdShedB  = "fd000000-0000-4000-8000-000000004002"
	// A retired shed, to prove the shed page lists active sheds only.
	fdShedRetired = "fd000000-0000-4000-8000-000000004003"
	// A second park, to prove park scoping.
	fdOtherPark = "fd000000-0000-4000-8000-000000003002"
)

func setupFeedDirectionDB(t *testing.T, ctx context.Context) (*Repository, *pgxpool.Pool) {
	t.Helper()
	pgtest.SkipIfNoDocker(t)
	pool := pgtest.StartPostgres(t, ctx)
	seedFeedDirectionScope(t, ctx, pool)
	return NewRepository(pool, 10*time.Second), pool
}

