// ---------------------------------------------------------------------------
// Key parity: the Go normalizer vs the database's feed_config_norm
// ---------------------------------------------------------------------------

// The single most valuable proof in this file.
//
// The generator resolves rations by joining live free-text values to authored labels IN MEMORY,
// so the Go NormalizeConfigKey must be byte-identical to the SQL feed_config_norm() that generated
// the stored keys. A one-character divergence does not raise an error anywhere: it makes a lookup
// miss, which makes a shed BLOCK, which is a shed that does not get fed over a hyphen.
func TestGoNormalizerMatchesDatabaseFeedConfigNormExactly(t *testing.T) {
	ctx := context.Background()
	_, pool := setupFeedDirectionDB(t, ctx)

	labels := []string{
		// The live cosmetic variants from the source sheet.
		"ICU-Kid", "ICU- kid", "ICU-  KID", "F2-Male", "F2- Male",
		"Non-Pregnant", "Milking Warmup", "Quarantine kids", "Mother", "K0",
		// The merged ration group, whose slash must survive normalization.
		"Beetal/Sirohi", "Anantapur Sheep",
		// The feed catalog.
		"Concentrate", "Baking Soda", "Dry Masoor Bhusa",
		// Adversarial separator/padding shapes.
		"  padded  ", "A___B---C   D", "-leading-", "trailing-", "a-_ b",
	}

	for _, label := range labels {
		var sqlKey string
		if err := pool.QueryRow(ctx, `SELECT feed_config_norm($1)`, label).Scan(&sqlKey); err != nil {
			t.Fatalf("feed_config_norm(%q): %v", label, err)
		}
		if goKey := domain.NormalizeConfigKey(label); goKey != sqlKey {
			t.Fatalf("normalizer divergence for %q: Go=%q SQL=%q -- an in-memory join would miss and block a well-authored shed",
				label, goKey, sqlKey)
		}
	}
}

// The stored *_key columns are GENERATED by the database. The snapshot builds its map keys from
// them via RateKey, and the generator looks up with raw live labels. This proves the round trip.
func TestStoredGeneratedKeysResolveThroughTheGoLookupKey(t *testing.T) {
	ctx := context.Background()
	repo, pool := setupFeedDirectionDB(t, ctx)

	if _, err := pool.Exec(ctx, `
INSERT INTO feed_ration_rates (tenant_id, park_id, ration_group_label, shed_tag_label, feed_item_label, grams_per_head, valid_from)
VALUES ($1::uuid, $2::uuid, 'Kid', 'ICU-Kid', 'Concentrate', 50.000, DATE '2026-01-01')`,
		fdTenant, fdPark); err != nil {
		t.Fatalf("seed rate: %v", err)
	}

	snapshot, err := repo.LoadConfigSnapshot(ctx, fdTenant, fdPark, businessDay(2026, 7, 19))
	if err != nil {
		t.Fatalf("LoadConfigSnapshot: %v", err)
	}

	// Looked up with the RAW LIVE spelling variant, not the authored one. This is exactly what the
	// generator does after resolving the tag.
	rate, ok := snapshot.RatesByKey[domain.RateKey("Kid", "ICU- kid", "Concentrate")]
	if !ok {
		t.Fatal("stored rate did not resolve through a raw live label variant")
	}
	if rate.GramsPerHead != "50.000" {
		t.Fatalf("grams_per_head = %q, want \"50.000\" (exact decimal string, never a float)", rate.GramsPerHead)
	}
}

