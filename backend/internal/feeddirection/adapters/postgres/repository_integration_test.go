// ---------------------------------------------------------------------------
// The session recipe (migration 000005)
// ---------------------------------------------------------------------------

// The slots are what stop the generator walking the whole feed_item_catalog. Four properties of
// that read are only observable against a real database, and each of them silently produces a WRONG
// FEED SHEET rather than an error:
//
//	SLOT ORDER      -- slot_no is packing order, not catalog order. Session 1 declares Hybrid before
//	                   Concentrate here precisely because the catalog's display_order is the reverse;
//	                   a query that forgot ORDER BY slot_no would still "pass" against a fixture
//	                   whose two orders agreed.
//	PER-SESSION     -- session 1's slots must not leak into session 2's row.
//	STATUS FILTER   -- a retired slot is no longer part of the recipe.
//	KEY PARITY      -- feed_item_key is GENERATED by feed_config_norm(), and it is the string the
//	                   generator matches against the rate grid's own generated key. If the two ever
//	                   diverge, a declared slot silently blocks.
func TestSessionSlotsLoadInPackingOrderScopedToTheirOwnSession(t *testing.T) {
	ctx := context.Background()
	repo, _ := setupFeedDirectionDB(t, ctx)

	snapshot, err := repo.LoadConfigSnapshot(ctx, fdTenant, fdPark, biztime.BusinessDayStart(time.Now()))
	if err != nil {
		t.Fatalf("load snapshot: %v", err)
	}
	if len(snapshot.Sessions) != 2 {
		t.Fatalf("sessions = %d, want 2 active", len(snapshot.Sessions))
	}

	// Session 1: both active slots, in slot_no order -- which is the REVERSE of catalog order.
	got := []string{}
	for _, item := range snapshot.Sessions[0].Items {
		got = append(got, item.Label)
	}
	if len(got) != 2 || got[0] != "Hybrid" || got[1] != "Concentrate" {
		t.Fatalf("session 1 slots = %v, want [Hybrid Concentrate] in slot_no order; the retired slot must be excluded", got)
	}

	// Session 2 declares only one slot. Session 1's second slot must not leak into it.
	if len(snapshot.Sessions[1].Items) != 1 || snapshot.Sessions[1].Items[0].Label != "Concentrate" {
		t.Fatalf("session 2 slots = %+v, want only Concentrate", snapshot.Sessions[1].Items)
	}

	// The GENERATED key must be the one the generator joins on, so a declared slot finds its rate.
	for _, item := range snapshot.Sessions[0].Items {
		if item.Key != domain.NormalizeConfigKey(item.Label) {
			t.Fatalf("slot %q stored key %q != Go NormalizeConfigKey %q; a declared slot would silently block",
				item.Label, item.Key, domain.NormalizeConfigKey(item.Label))
		}
	}

	// The union the generator resolves rates against: distinct, first-declared order.
	planned := []string{}
	for _, item := range snapshot.PlannedFeedItems() {
		planned = append(planned, item.Label)
	}
	if len(planned) != 2 || planned[0] != "Hybrid" || planned[1] != "Concentrate" {
		t.Fatalf("planned items = %v, want [Hybrid Concentrate] deduped across sessions", planned)
	}
}

