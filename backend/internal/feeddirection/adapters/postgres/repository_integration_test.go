// The snapshot must load what was in force ON THE TARGET DAY. Loading the currently-open row
// instead would reprint history with today's numbers.
func TestSnapshotLoadsTheRateInForceOnTheTargetDayNotTheOpenRow(t *testing.T) {
	ctx := context.Background()
	repo, pool := setupFeedDirectionDB(t, ctx)

	// A superseded window (closed on 2026-07-01) and its successor (still open).
	if _, err := pool.Exec(ctx, `
INSERT INTO feed_ration_rates (tenant_id, park_id, ration_group_label, shed_tag_label, feed_item_label, grams_per_head, valid_from, valid_to)
VALUES ($1::uuid, $2::uuid, 'Beetal/Sirohi', 'Non-Pregnant', 'Concentrate', 150.000, DATE '2026-01-01', DATE '2026-07-01'),
       ($1::uuid, $2::uuid, 'Beetal/Sirohi', 'Non-Pregnant', 'Concentrate', 200.000, DATE '2026-07-01', NULL)`,
		fdTenant, fdPark); err != nil {
		t.Fatalf("seed rates: %v", err)
	}

	key := domain.RateKey("Beetal/Sirohi", "Non-Pregnant", "Concentrate")

	cases := []struct {
		name string
		day  time.Time
		want string
	}{
		{name: "today takes the open row", day: businessDay(2026, 7, 19), want: "200.000"},
		// The window is [valid_from, valid_to): the successor's first day is the day it takes effect.
		{name: "the changeover day takes the successor", day: businessDay(2026, 7, 1), want: "200.000"},
		{name: "the day before takes the superseded row", day: businessDay(2026, 6, 30), want: "150.000"},
		{name: "a back-dated day reprints the historical rate", day: businessDay(2026, 3, 15), want: "150.000"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			snapshot, err := repo.LoadConfigSnapshot(ctx, fdTenant, fdPark, tc.day)
			if err != nil {
				t.Fatalf("LoadConfigSnapshot: %v", err)
			}
			rate, ok := snapshot.RatesByKey[key]
			if !ok {
				t.Fatalf("no rate in force on %s", biztime.BusinessDate(tc.day))
			}
			if rate.GramsPerHead != tc.want {
				t.Fatalf("grams_per_head on %s = %q, want %q",
					biztime.BusinessDate(tc.day), rate.GramsPerHead, tc.want)
			}
		})
	}

	// Before the first window opens there is NO rate -- and that must read as absent (blocking),
	// not as a zero.
	early, err := repo.LoadConfigSnapshot(ctx, fdTenant, fdPark, businessDay(2025, 12, 31))
	if err != nil {
		t.Fatalf("LoadConfigSnapshot: %v", err)
	}
	if _, ok := early.RatesByKey[key]; ok {
		t.Fatal("a rate resolved before its first window opened")
	}
}

