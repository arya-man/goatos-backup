func humanLabel(key string) string {
	switch key {
	case "goat_id":
		return "Goat ID"
	case "next_action":
		return "Next action"
	case "effective_date":
		return "Effective date"
	case "linked_sop":
		return "Linked SOP"
	case "rule_count":
		return "Rule count"
	case "source_obligation":
		return "Source obligation"
	case "weight":
		return "WT"
	case "when":
		return "Time"
	case "holding_farm_supplier":
		return "Holding farm · supplier"
	case "vaccination_hf":
		return "Vaccination · at HF"
	case "health_selection":
		return "Health / Selection"
	case "shed_stage":
		return "Shed · stage"
	case "drive_due":
		return "Drive · due"
	case "work_state":
		return "Work state"
	case "owner_chain":
		return "Owner chain"
	case "sop_proof_verify":
		return "SOP · proof · verify"
	case "animal_stage":
		return "Animal stage"
	case "animal_ids":
		return "Animal IDs"
	case "source_entry":
		return "Source entry"
	case "current_stage":
		return "Current stage"
	case "arrival_state":
		return "Arrival state"
	case "entry_date":
		return "Entry date"
	default:
		out := []rune(key)
		for i, r := range out {
			if r == '_' {
				out[i] = ' '
			}
		}
		if len(out) > 0 && out[0] >= 'a' && out[0] <= 'z' {
			out[0] = out[0] - ('a' - 'A')
		}
		return string(out)
	}
}

